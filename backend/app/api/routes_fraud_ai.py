@router.post("/analyze-transaction")
def analyze_transaction_data(req: TransactionAnalysisRequest):
    """
    Runs Bayes' Theorem update and AO* Search over transactional data parameters.
    """
    detected_evidences = []
    flags = req.flags or {}

    # 1. Amount Anomaly rule
    if req.amount >= 25000 or flags.get("flag_amount_anomaly"):
        detected_evidences.append({
            "id": "amount_anomaly",
            "details": f"Transaction amount ₹{req.amount:,.2f} deviates significantly from standard retail threshold (>3.5σ outlier)."
        })

    # 2. Invalid UTR check
    if flags.get("flag_invalid_utr") or (req.utr and not re.match(r'^\d{12}$', str(req.utr))):
        detected_evidences.append({
            "id": "utr_invalid_syntax",
            "details": f"UTR Reference ID '{req.utr or 'NOT_PROVIDED'}' violates NPCI 12-digit numeric checksum standard."
        })

    # 3. Visual Tampering
    if flags.get("flag_visual_tamper"):
        detected_evidences.append({
            "id": "visual_tampering",
            "details": "Digital paste / font height discrepancy detected."
        })

    # 4. Beneficiary Mismatch
    if flags.get("flag_beneficiary_mismatch"):
        detected_evidences.append({
            "id": "beneficiary_mismatch",
            "details": f"Beneficiary '{req.beneficiary_account}' not present in verified counterparty whitelist."
        })

    # 5. Time Velocity Anomaly
    if flags.get("flag_time_anomaly"):
        detected_evidences.append({
            "id": "time_velocity_anomaly",
            "details": "Nocturnal burst window (2:00 AM - 5:00 AM) with rapid sequence."
        })

    # 6. Missing Watermark
    if flags.get("flag_missing_watermark"):
        detected_evidences.append({
            "id": "missing_watermark_elements",
            "details": "Bank / NPCI verification seal absent."
        })

    # Run Bayes' Theorem
    bayes_res = bayesian_engine.evaluate(detected_evidences)

    # Run AO* Search
    evidence_map = {e["id"]: e for e in detected_evidences}
    graph = ao_star_engine.build_fraud_graph(evidence_map)
    ao_res = ao_star_engine.run_ao_star(graph, root_id="GOAL_FRAUD")

    # Run Disjoint Set Union (DSU / Union-Find) Syndicate & Cycle Detection
    dsu_res = dsu_fraud_evaluator.analyze_syndicate_clustering(
        current_sender=req.transaction_id or "ACC-SRC",
        current_receiver=req.beneficiary_account or "counterparty@bank",
        amount=req.amount,
        utr=req.utr
    )

    is_fraud = bayes_res.posterior_probability >= 0.50 or dsu_res.get("candidate_causes_cycle", False)
    agent_advisory = receipt_fraud_agent.generate_agent_advisory(
        image_path=None,
        extracted={"amount": req.amount, "utr": req.utr, "payee": req.beneficiary_account},
        forensics={"has_clipping_artifacts": flags.get("flag_visual_tamper", False)},
        bayes_result=bayes_res,
        ao_result=ao_res
    )

    return {
        "success": True,
        "transaction_id": req.transaction_id,
        "amount": req.amount,
        "verdict": {
            "title": "FRAUD DETECTED" if is_fraud else "TRANSACTION VERIFIED",
            "is_fraud": is_fraud,
            "fraud_probability": bayes_res.posterior_probability,
            "risk_score_100": bayes_res.risk_score_100,
            "risk_level": bayes_res.risk_level,
            "recommendation": "Block transaction and alert risk operations." if is_fraud else "Approve transaction."
        },
        "gemini_agent_advisory": agent_advisory,
        "bayesian_analysis": {
            "is_applicable": True,
            "prior_probability": bayes_res.prior_probability,
            "posterior_probability": bayes_res.posterior_probability,
            "formula_latex": bayes_res.formula_latex,
            "explanation": bayes_res.explanation_summary,
            "steps": [
                {
                    "step_num": s.step_num,
                    "evidence_name": s.evidence_name,
                    "prior_prob": s.prior_probability,
                    "bayes_factor": s.bayes_factor,
                    "posterior_prob": s.posterior_probability,
                    "delta_pct": s.delta_risk,
                    "explanation": s.explanation
                }
                for s in bayes_res.steps
            ]
        },
        "ao_star_search": {
            "is_applicable": True,
            "root_id": ao_res.root_id,
            "is_fraud_proved": ao_res.is_fraud_proved,
            "optimal_cost": ao_res.optimal_cost,
            "explanation": ao_res.explanation,
            "proof_tree_nodes": ao_res.proof_tree_nodes,
            "proof_tree_edges": ao_res.proof_tree_edges,
            "full_graph": ao_res.graph_dict,
            "traversal_log": ao_res.traversal_log
        },
        "dsu_clustering": dsu_res
    }


@router.post("/analyze-screenshot")
async def analyze_fraud_screenshot(
    file: UploadFile = File(...),
    flag_visual_tamper: Optional[bool] = Form(None),
    flag_invalid_utr: Optional[bool] = Form(None),
    flag_amount_anomaly: Optional[bool] = Form(None),
    flag_beneficiary_mismatch: Optional[bool] = Form(None),
    flag_missing_watermark: Optional[bool] = Form(None)
):
    """
    Accepts an uploaded payment screenshot or receipt voucher image.
    Executes OpenCV image forensics + OCR + Bayes' Theorem + AO* graph search.
    """
    try:
        suffix = Path(file.filename or "screenshot.png").suffix or ".png"
        safe_filename = f"fraud_{int(time.time())}_{re.sub(r'[^a-zA-Z0-9]', '_', Path(file.filename or 'img').stem)}{suffix}"
        target_path = UPLOAD_DIR / safe_filename

        content = await file.read()
        with open(target_path, "wb") as f:
            f.write(content)

        overrides = {}
        if flag_visual_tamper is not None:
            overrides["flag_visual_tamper"] = flag_visual_tamper
        if flag_invalid_utr is not None:
            overrides["flag_invalid_utr"] = flag_invalid_utr
        if flag_amount_anomaly is not None:
            overrides["flag_amount_anomaly"] = flag_amount_anomaly
        if flag_beneficiary_mismatch is not None:
            overrides["flag_beneficiary_mismatch"] = flag_beneficiary_mismatch
        if flag_missing_watermark is not None:
            overrides["flag_missing_watermark"] = flag_missing_watermark

        result = receipt_fraud_agent.inspect_and_reason(
            image_path=str(target_path),
            manual_override=overrides if overrides else None
        )

        result["image_url"] = f"/api/fraud-ai/uploads/{safe_filename}"
        result["filename"] = file.filename
        return result
    except Exception as e:
        import traceback
        traceback.print_exc()
        raise HTTPException(status_code=500, detail=f"Multimodal screenshot fraud analysis error: {str(e)}")
